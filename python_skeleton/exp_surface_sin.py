"""
This code is generated by claude.

Projection of a regular periodic grid onto a sine interface.

The periodic cell contains two materials separated by the curve

    y = h0 + A sin(w x + phi),

the lower material below the curve and the background above it. The
application (cyclic pulling of the cell, stress/deformation at the surface)
is NOT simulated here; this script only projects the regular mesh nodes onto
the interface and saves/plots the result.

Nodes on the bottom (y = 0) boundary stay fixed. On the left/right boundary
(x = 0 = Lx) the node closest to the interface moves only up/down onto it;
the other boundary nodes stay fixed. No spring relaxation is applied.

Input: the analytical curve or fine edge coordinates on the curve.
Output: projected nodal coordinates, shape (2, Nx, Ny).
"""

import sys
import os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '../..')))

from datetime import datetime
from pathlib import Path

import numpy as np
import matplotlib.pyplot as plt
from muFFTTO import domain
from muFFTTO.visualization_utils import plot_field_on_grid
from muFFTTO.grid_adaptation_methods_Zecevic import (
    project_grid_to_sine_surface,
    sine_interface_cell_labels,
    periodic_cell_quadrature_det_F,
    build_periodic_plot_coordinates,
)

# =============================================================
# USER PARAMETERS
# =============================================================
# problem configuration
problem_type = 'conductivity'
discretization_type = 'finite_element'
element_type = 'bilinear_rectangle'
domain_size = (1, 1)
number_of_pixels = (32,32)

# sine interface y = h0 + A sin(w x + phi); w must fit Lx: w = 2 pi n / Lx
h0 = 0.6                              # mean height (mid-upper part of the cell)
A = 0.1                               # amplitude -> curve in [0.5, 0.7]
n_periods = 1                         # number of periods over Lx
w = 4.0 * np.pi * n_periods / domain_size[0]
phi = 0.5                             # phase

# input of the projection
surface_input = "analytical"          # "analytical" or "fine_edge"
nb_fine_edge_points = 2048            # only for "fine_edge": samples on the curve
search_range = 0.7                    # only for "fine_edge": in units of the coarse spacing
search_shape = "circle"               # only for "fine_edge": "circle" or "square"

# =============================================================
# OUTPUT
# =============================================================
OUTPUT_ROOT = Path(__file__).resolve().parent / "output_surface_sin"

RUN_TAG = (
    f"N{number_of_pixels[0]}x{number_of_pixels[1]}"
    f"_L{domain_size[0]:g}x{domain_size[1]:g}"
    f"_h{h0:g}_A{A:g}_n{n_periods}_phi{phi:g}"
    f"_{surface_input}"
    f"_{datetime.now().strftime('%Y%m%d-%H%M%S')}"
)

OUTPUT_DIR = OUTPUT_ROOT / RUN_TAG
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def plot_field_and_save(coordinates_for_plot, field_to_plot, name, save_path):
    """Call plot_field_on_grid and save the figure right before plt.show()."""
    original_show = plt.show

    def _save_then_show(*args, **kwargs):
        plt.gcf().savefig(save_path, dpi=300, bbox_inches="tight")
        return original_show(*args, **kwargs)

    plt.show = _save_then_show
    try:
        plot_field_on_grid(coordinates_for_plot=coordinates_for_plot, field_to_plot=field_to_plot, name=name)
    finally:
        plt.show = original_show


my_cell = domain.PeriodicUnitCell(domain_size=domain_size,
                                  problem_type=problem_type)
discretization = domain.Discretization(cell=my_cell,
                                       nb_of_pixels_global=number_of_pixels,
                                       discretization_type=discretization_type,
                                       element_type=element_type)

# PHYSICAL reference coordinates, shape (2, Nx, Ny)
ref_grid_coords_ixyz = np.array(discretization.get_nodal_points_coordinates().s[:, 0, ...])

# =============================================================
# PROJECTION (WORKFLOW C: SINE INTERFACE)
# =============================================================
if surface_input == "analytical":
    fine_edge_coords = None
elif surface_input == "fine_edge":
    # fine edge coordinates sampled on the curve, shape (2, n)
    x_fine = np.linspace(0.0, domain_size[0], nb_fine_edge_points, endpoint=False)
    fine_edge_coords = np.stack((x_fine, h0 + A * np.sin(w * x_fine + phi)))
else:
    raise ValueError(f"surface_input must be 'analytical' or 'fine_edge', got '{surface_input}'")

coarse_def_grid_coords_inxyz = project_grid_to_sine_surface(
    ref_grid_coords_ixyz=ref_grid_coords_ixyz,
    h0=h0,
    A=A,
    w=w,
    phi=phi,
    fine_edge_coords=fine_edge_coords,
    search_range=search_range,
    search_shape=search_shape,
)

# cell labels for plotting: 1 = lower material, 0 = background
coarse_phase_field_geom = sine_interface_cell_labels(ref_grid_coords_ixyz, h0, A, w, phi)

np.save(OUTPUT_DIR / f"coarse_def_grid_coords_inxyz_{RUN_TAG}.npy", coarse_def_grid_coords_inxyz)
np.save(OUTPUT_DIR / f"coarse_phase_field_geom_{RUN_TAG}.npy", coarse_phase_field_geom)

# ---------- DIAGNOSTICS (comment out to silence) ----------
Lx, Ly = map(float, domain_size)
moved = np.any(coarse_def_grid_coords_inxyz != ref_grid_coords_ixyz, axis=0)
mx, my = coarse_def_grid_coords_inxyz[:, moved]
dist_to_curve = np.abs(my - (h0 + A * np.sin(w * mx + phi)))
det_F_q, inverted = periodic_cell_quadrature_det_F(coarse_def_grid_coords_inxyz, ref_grid_coords_ixyz, Lx, Ly)
print("===== PROJECTION DIAGNOSTICS =====")
print(f"{'surface_input':35s}: {surface_input}")
print(f"{'n_projected_nodes':35s}: {int(np.count_nonzero(moved))}")
print(f"{'max |y - f(x)| of projected nodes':35s}: {dist_to_curve.max() if dist_to_curve.size else 0.0:.3e}")
print(f"{'min det(F) (quadrature)':35s}: {det_F_q.min():.6f}")
print(f"{'inverted cells':35s}: {inverted}")
print("==================================")
# ----------------------------------------------------------

# --------------------------------
# PLOTS
# --------------------------------
# coordinates used for PLOTTING only (with periodic end nodes, shape (2, Nx+1, Ny+1))
x_plot = build_periodic_plot_coordinates(
    def_coords=coarse_def_grid_coords_inxyz,
    ref_coords=ref_grid_coords_ixyz,
    domain_size=domain_size,
)
plot_field_and_save(x_plot, coarse_phase_field_geom, 'Material',
                    OUTPUT_DIR / f"Material_{RUN_TAG}.png")
plot_field_and_save(x_plot, det_F_q.min(axis=0), 'min det(F)',
                    OUTPUT_DIR / f"detF_{RUN_TAG}.png")

# projected grid with the analytical curve
fig, ax = plt.subplots(figsize=(6, 6))
ax.plot(x_plot[0], x_plot[1], color="k", lw=0.4)
ax.plot(x_plot[0].T, x_plot[1].T, color="k", lw=0.4)
x_curve = np.linspace(0.0, Lx, 1000)
ax.plot(x_curve, h0 + A * np.sin(w * x_curve + phi), color="tab:red", lw=1.2, label="interface")
ax.plot(mx, my, "o", color="tab:blue", ms=2.5, label="projected nodes")
ax.set_aspect("equal")
ax.set_xlabel("x")
ax.set_ylabel("y")
ax.set_title("Projected grid")
ax.legend(loc="lower right")
fig.tight_layout()
fig.savefig(OUTPUT_DIR / f"Projected_grid_{RUN_TAG}.png", dpi=300, bbox_inches="tight")
plt.show()

print("outputs saved in:", OUTPUT_DIR)
